"""Deterministic generator for fixed-latency, multi-iteration CORDIC RTL.

The datapath performs 1, 2 or 4 CORDIC micro-iterations per active compute
cycle. The external response pulse remains fixed at the baseline's 16-cycle
latency so the existing cycle-accurate EQY contract remains meaningful.
"""
from __future__ import annotations

import hashlib
from pathlib import Path

from .harness import ROOT

SUPPORTED_ITERATIONS_PER_CYCLE = (1, 2, 4)
TOTAL_ITERATIONS = 16
FIXED_RESPONSE_CYCLES = 16


def generate_cordic_rtl(iterations_per_cycle: int) -> str:
    """Return deterministic SystemVerilog for one unroll factor."""
    if (isinstance(iterations_per_cycle, bool)
            or not isinstance(iterations_per_cycle, int)
            or iterations_per_cycle not in SUPPORTED_ITERATIONS_PER_CYCLE):
        raise ValueError(
            f"iterations_per_cycle must be one of {SUPPORTED_ITERATIONS_PER_CYCLE}"
        )
    groups = TOTAL_ITERATIONS // iterations_per_cycle
    lines = [
        "// Generated by chiprd.architecture_generator; do not edit by hand.",
        f"// iterations_per_cycle={iterations_per_cycle}; fixed_response_cycles={FIXED_RESPONSE_CYCLES}.",
        "// The internal CORDIC state is deliberately renamed so EQY compares the",
        "// externally visible transaction trace rather than unlike micro-architectures.",
        "module cordic_rotator (",
        "    input  logic clk,",
        "    input  logic rst,",
        "    input  logic input_valid,",
        "    input  logic signed [15:0] angle_in,",
        "    output logic output_valid,",
        "    output logic signed [15:0] x_out,",
        "    output logic signed [15:0] y_out",
        ");",
        "    logic busy;",
        "    logic [4:0] cycle_count;",
        "    logic [4:0] iteration_base;",
        "    logic signed [31:0] qx, qy, qz;",
        "",
        "    function automatic signed [31:0] atan_value(input logic [4:0] index);",
        "        case (index)",
    ]
    atan = [6434, 3798, 2007, 1019, 511, 256, 128, 64,
            32, 16, 8, 4, 2, 1, 0, 0]
    for index, value in enumerate(atan):
        lines.append(f"            5'd{index}: atan_value = 32'sd{value};")
    lines.extend([
        "            default: atan_value = 32'sd0;",
        "        endcase",
        "    endfunction",
        "",
    ])

    prev_x, prev_y, prev_z = "qx", "qy", "qz"
    for index in range(iterations_per_cycle):
        suffix = str(index)
        shift = f"(iteration_base + 5'd{index})"
        x_shift = f"gx_x_shift_{suffix}"
        y_shift = f"gx_y_shift_{suffix}"
        next_x, next_y, next_z = f"gx_x_{suffix}", f"gx_y_{suffix}", f"gx_z_{suffix}"
        lines.extend([
            f"    wire signed [31:0] {x_shift} = {prev_x} >>> {shift};",
            f"    wire signed [31:0] {y_shift} = {prev_y} >>> {shift};",
            f"    wire signed [31:0] {next_x} = ({prev_z} >= 0) ? ({prev_x} - {y_shift}) : ({prev_x} + {y_shift});",
            f"    wire signed [31:0] {next_y} = ({prev_z} >= 0) ? ({prev_y} + {x_shift}) : ({prev_y} - {x_shift});",
            f"    wire signed [31:0] {next_z} = ({prev_z} >= 0) ? ({prev_z} - atan_value({shift})) : ({prev_z} + atan_value({shift}));",
            "",
        ])
        prev_x, prev_y, prev_z = next_x, next_y, next_z

    lines.extend([
        "    always_ff @(posedge clk) begin",
        "        if (rst) begin",
        "            busy <= 1'b0;",
        "            cycle_count <= 0;",
        "            iteration_base <= 0;",
        "            qx <= 0;",
        "            qy <= 0;",
        "            qz <= 0;",
        "            x_out <= 0;",
        "            y_out <= 0;",
        "            output_valid <= 1'b0;",
        "        end else begin",
        "            output_valid <= 1'b0;",
        "            if (!busy && input_valid) begin",
        "                busy <= 1'b1;",
        "                cycle_count <= 0;",
        "                iteration_base <= 0;",
        "                qx <= 9949;",
        "                qy <= 0;",
        "                qz <= {{16{angle_in[15]}}, angle_in};",
        "            end else if (busy) begin",
        f"                if (cycle_count < 5'd{groups}) begin",
        f"                    qx <= {prev_x};",
        f"                    qy <= {prev_y};",
        f"                    qz <= {prev_z};",
        f"                    iteration_base <= iteration_base + 5'd{iterations_per_cycle};",
        "                end",
        f"                if (cycle_count == 5'd{FIXED_RESPONSE_CYCLES - 1}) begin",
        "                    busy <= 1'b0;",
        "                    output_valid <= 1'b1;",
        f"                    x_out <= (cycle_count < 5'd{groups}) ? {prev_x}[15:0] : qx[15:0];",
        f"                    y_out <= (cycle_count < 5'd{groups}) ? {prev_y}[15:0] : qy[15:0];",
        "                end else begin",
        "                    cycle_count <= cycle_count + 1'b1;",
        "                end",
        "            end",
        "        end",
        "    end",
        "endmodule",
        "",
    ])
    return "\n".join(lines)


def write_generated_architectures(
    output_dir: Path,
    *,
    configurations: tuple[int, ...] = (2, 4),
    check: bool = False,
) -> dict:
    """Write or verify generated RTL under the repository root."""
    output_dir = Path(output_dir)
    cursor = output_dir
    while cursor != cursor.parent:
        if cursor.is_symlink():
            raise ValueError("Generated RTL output path must not traverse symlinks")
        cursor = cursor.parent
    resolved = output_dir.resolve()
    try:
        resolved.relative_to(ROOT.resolve())
    except ValueError as exc:
        raise ValueError("Generated RTL output directory must remain inside the repository") from exc
    if len(set(configurations)) != len(configurations):
        raise ValueError("Duplicate architecture configurations are not allowed")
    if not configurations:
        raise ValueError("At least one architecture configuration is required")
    for value in configurations:
        if (isinstance(value, bool) or not isinstance(value, int)
                or value not in SUPPORTED_ITERATIONS_PER_CYCLE):
            raise ValueError(f"Unsupported iterations_per_cycle: {value}")

    if not check:
        resolved.mkdir(parents=True, exist_ok=True)
    results = []
    for value in configurations:
        path = resolved / f"cordic_iter{value}.sv"
        if path.is_symlink():
            raise ValueError(f"Generated RTL path must not be a symlink: {path}")
        expected = generate_cordic_rtl(value)
        digest = hashlib.sha256(expected.encode("utf-8")).hexdigest()
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                raise ValueError(f"Generated RTL is stale or missing: {path.relative_to(ROOT)}")
            status = "verified"
        else:
            path.write_text(expected, encoding="utf-8")
            status = "generated"
        results.append({
            "iterations_per_cycle": value,
            "path": path.relative_to(ROOT).as_posix(),
            "sha256": digest,
            "status": status,
        })
    return {
        "status": "pass",
        "generator": "cordic_fixed_latency_unroll_v1",
        "fixed_response_cycles": FIXED_RESPONSE_CYCLES,
        "total_iterations": TOTAL_ITERATIONS,
        "configurations": results,
    }
